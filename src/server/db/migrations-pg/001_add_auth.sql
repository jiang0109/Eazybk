-- =============================================================================
--  迁移 001：加上登录功能（PostgreSQL 版）
-- =============================================================================
--  和 SQLite 版的 001_add_auth.sql 做的是同一件事：
--  给"已经存在数据的库"加登录字段，而不是删库重建。
--
--  为什么这次不重建？
--    库里有真实数据，删了不可惜才怪。而且"给线上正在使用的库加字段"
--    是真实项目里天天在做的事，必须会。
--
--  写迁移的铁律（两种数据库都一样）：
--    - 只能追加，不能修改已经发布过的迁移
--    - 不要依赖应用代码，纯 SQL，这样它能在任何版本的应用下跑
--
--  SQLite vs PG 的差异（这个文件里能看出来）：
--    - SQLite 加列：ALTER TABLE ... ADD COLUMN（能加列但不能改类型）
--    - PG   加列：同样的语法，而且**可以**加约束、改类型、加默认值，
--               功能强得多，但也要更小心（改类型会重写整张表）
-- =============================================================================

-- -----------------------------------------------------------------------------
-- 1. users 表加登录字段
-- -----------------------------------------------------------------------------

-- 登录名。用 username 而不是 email：这个 App 不发邮件
-- （免费托管平台的邮件额度很低），拿用户名当登录标识最省事。
ALTER TABLE users ADD COLUMN IF NOT EXISTS username text;

-- 密码哈希（scrypt，含 salt），**永远不存明文**。
-- 允许 NULL：演示账号没有密码（只能一键体验），迁移前的旧用户也没有。
ALTER TABLE users ADD COLUMN IF NOT EXISTS password_hash text;

-- 演示账号标记。
--   SQLite 里用 INTEGER + CHECK (is_demo IN (0,1))，因为 SQLite 没有布尔类型；
--   PG 有真正的 boolean，直接用，不需要 CHECK —— 类型系统已经保证了。
ALTER TABLE users ADD COLUMN IF NOT EXISTS is_demo boolean NOT NULL DEFAULT false;

-- created_at 在基线 schema 里已经存在，这里不重复加
-- （SQLite 版我第一次就多加了这一列，报 duplicate column name 才发现的）

-- 用户名唯一。部分索引跳过 NULL —— 没有用户名的旧用户不该被这个约束卡住。
-- 这条写法 SQLite 和 PG 完全一样。
CREATE UNIQUE INDEX IF NOT EXISTS ux_users_username
  ON users (username) WHERE username IS NOT NULL;

-- 用户名长度约束。加在已有表上要用 DO 块判断是否已存在，
-- 因为 PG 不支持 "ADD CONSTRAINT IF NOT EXISTS"。
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'users_username_length'
  ) THEN
    ALTER TABLE users
      ADD CONSTRAINT users_username_length
      CHECK (username IS NULL OR length(username) BETWEEN 3 AND 20);
  END IF;
END $$;

-- -----------------------------------------------------------------------------
-- 2. 会话表
-- -----------------------------------------------------------------------------
-- 会话存数据库而不是塞进 JWT 的原因见 README：
-- 数据库会话可以**随时撤销**（退出登录、改密码踢下线），JWT 做不到。
--
-- 表里存的是令牌的 SHA-256，不是令牌原文 —— 数据库泄露也不能直接拿去登录。
CREATE TABLE IF NOT EXISTS sessions (
  token_hash text PRIMARY KEY,
  user_id    bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now(),
  expires_at timestamptz NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_sessions_user ON sessions (user_id);
CREATE INDEX IF NOT EXISTS idx_sessions_expires ON sessions (expires_at);

-- -----------------------------------------------------------------------------
-- 3. 登录尝试记录（防暴力破解）
-- -----------------------------------------------------------------------------
-- 为什么落库而不是放内存？内存计数在进程重启后就清空了，
-- 攻击者只要等你重启就能继续爆破。
CREATE TABLE IF NOT EXISTS login_attempts (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username     text NOT NULL,
  attempted_at timestamptz NOT NULL DEFAULT now(),
  success      boolean NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_login_attempts_lookup
  ON login_attempts (username, attempted_at DESC);

-- -----------------------------------------------------------------------------
-- 4. 创建演示账号
-- -----------------------------------------------------------------------------
-- password_hash 故意留成 NULL：演示账号不允许密码登录，
-- 只能走专门的"一键体验"接口。这样不需要在代码或仓库里硬编码演示密码。
--
-- ⚠️ 这里踩过一个坑，值得记下来：
--    最初写的是 `ON CONFLICT (username) DO NOTHING`，结果报
--        error: there is no unique or exclusion constraint
--               matching the ON CONFLICT specification
--    原因是 ux_users_username 是一个**部分唯一索引**（带 WHERE username IS NOT NULL），
--    PG 要求 ON CONFLICT 的目标必须和索引定义完全匹配，
--    部分索引得写成 `ON CONFLICT (username) WHERE username IS NOT NULL` —
--    很容易漏掉那个 WHERE。
--
--    而且更根本的问题：全新库里基线 schema 已经建好演示账号了，
--    这句插入本来就是多余的（只会走冲突分支）。
--    所以改用 WHERE NOT EXISTS —— 意图更直白，也不挑索引形态。
INSERT INTO users (name, username, password_hash, is_demo)
SELECT '演示账号', 'demo', NULL, true
WHERE NOT EXISTS (SELECT 1 FROM users WHERE username = 'demo');
