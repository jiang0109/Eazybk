-- =============================================================================
--  记账 App —— 表结构（PostgreSQL 版）
-- =============================================================================
--  这是从 SQLite 版迁移过来的。设计决策完全不变，只有方言变了。
--  下面凡是写法不同但**意图相同**的地方都标了 "SQLite vs PG"，
--  方便你对照两份文件看差异 —— 这本身就是一次很好的方言学习。
--
--  执行：npm run db:init（会读 .env 里的 DATABASE_URL）
-- =============================================================================

-- -----------------------------------------------------------------------------
-- 用户
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS users (
  -- SQLite: INTEGER PRIMARY KEY AUTOINCREMENT
  -- PG    : BIGINT + IDENTITY。注意 PG 的 INTEGER 只有 32 位，
  --         主键用 BIGINT 是习惯做法（避免多年后需要迁移）。
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name          text NOT NULL,
  username      text,
  password_hash text,
  is_demo       boolean NOT NULL DEFAULT false,
  created_at    timestamptz NOT NULL DEFAULT now(),

  -- 用户名长度/字符集的约束放在数据库层，不只靠应用校验
  CHECK (username IS NULL OR length(username) BETWEEN 3 AND 20)
);

-- 用户名唯一。
-- SQLite 和 PG 都支持"部分索引"，用法完全一样 —— 跳过 NULL 是为了兼容
-- 没有用户名的旧用户（他们本来也无法登录）。
CREATE UNIQUE INDEX IF NOT EXISTS ux_users_username
  ON users (username) WHERE username IS NOT NULL;

-- -----------------------------------------------------------------------------
-- 会话
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS sessions (
  -- 令牌的 SHA-256（hex）。存哈希而不是原文：数据库泄露也不能直接拿去登录。
  -- 用 text 作主键：hex 字符串固定 64 字符，做主键没有性能问题。
  token_hash text PRIMARY KEY,
  user_id    bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now(),
  -- SQLite 里是 TEXT 存 'YYYY-MM-DD HH:MM:SS' 并和 datetime('now') 比字符串；
  -- PG 里用真正的 timestamptz，比较靠时间运算（now() + interval），语义更准确。
  expires_at timestamptz NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_sessions_user ON sessions (user_id);
CREATE INDEX IF NOT EXISTS idx_sessions_expires ON sessions (expires_at);

-- -----------------------------------------------------------------------------
-- 登录尝试记录（防暴力破解）
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS login_attempts (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username     text NOT NULL,
  attempted_at timestamptz NOT NULL DEFAULT now(),
  success      boolean NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_login_attempts_lookup
  ON login_attempts (username, attempted_at DESC);

-- -----------------------------------------------------------------------------
-- 账户
--
-- 关键点 1：金额一律用整数存"分"，绝不用浮点存"元"。
--           PG 里有两个整型选择：INTEGER（32 位，上限约 2147 万）
--           和 BIGINT（64 位）。**必须用 BIGINT** —— 因为应用允许单笔
--           最大 1 亿分，如果哪天出现"余额比单笔大"的汇总场景，
--           32 位会直接溢出报错（SQLite 的 INTEGER 天生是 64 位，反而没这个问题）。
--
-- 关键点 2：balance_cents 是派生数据，由触发器维护（见文件末尾）。
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS accounts (
  id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id               bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  name                  text NOT NULL,
  type                  text NOT NULL CHECK (type IN ('cash','bank','credit','ewallet','investment')),
  initial_balance_cents bigint NOT NULL DEFAULT 0,
  balance_cents         bigint NOT NULL DEFAULT 0,
  currency              text NOT NULL DEFAULT 'CNY',
  sort_order            integer NOT NULL DEFAULT 0,
  created_at            timestamptz NOT NULL DEFAULT now(),

  UNIQUE (user_id, name),
  CHECK (length(btrim(name)) > 0)
);

-- -----------------------------------------------------------------------------
-- 分类（支持二级分类：parent_id 自引用）
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS categories (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  name       text NOT NULL,
  kind       text NOT NULL CHECK (kind IN ('expense','income')),
  parent_id  bigint REFERENCES categories(id) ON DELETE CASCADE,
  icon       text,
  sort_order integer NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now(),

  CHECK (parent_id IS NULL OR parent_id <> id),
  CHECK (length(btrim(name)) > 0)
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_categories_root_name
  ON categories (user_id, kind, name) WHERE parent_id IS NULL;

CREATE UNIQUE INDEX IF NOT EXISTS ux_categories_child_name
  ON categories (user_id, parent_id, name) WHERE parent_id IS NOT NULL;

CREATE INDEX IF NOT EXISTS idx_categories_parent ON categories (parent_id);

-- -----------------------------------------------------------------------------
-- 流水（核心表）
--
-- 设计要点 1：收入和支出放同一张表，用符号表示方向（>0 流入，<0 流出），
--             于是 SUM(amount_cents) 天然就是净额。
-- 设计要点 2：type 与 category_id 的联动约束（见下方 CHECK）。
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS transactions (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id      bigint NOT NULL REFERENCES users(id)    ON DELETE CASCADE,
  account_id   bigint NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
  category_id  bigint          REFERENCES categories(id) ON DELETE RESTRICT,
  type         text NOT NULL CHECK (type IN ('expense','income','transfer')),
  amount_cents bigint NOT NULL CHECK (amount_cents <> 0),
  description  text NOT NULL DEFAULT '',

  -- 记账日期（业务日期）。和 created_at（录入时间）是两回事：
  -- 你可能今天补记上周日的消费。所有报表一律按 occurred_on 统计。
  --
  -- SQLite vs PG 的第一个重要差异：
  --   SQLite 没有原生日期类型，用 TEXT + GLOB 约束校验格式；
  --   PG 有真正的 date 类型，**写不进非法日期**（'2026-02-31' 会被直接拒绝），
  --   所以那条 GLOB 约束在这里是多余的 —— 类型系统本身就保证了。
  occurred_on  date NOT NULL,

  created_at   timestamptz NOT NULL DEFAULT now(),
  updated_at   timestamptz NOT NULL DEFAULT now(),

  -- 【本表最重要的一条约束】分类该不该填由 type 决定。
  -- 这条约束 SQLite 和 PG 完全一样 —— 好的约束设计是跨方言的。
  CHECK (
    (type =  'transfer' AND category_id IS NULL)
    OR
    (type <> 'transfer' AND category_id IS NOT NULL)
  )
);

-- 索引：列顺序有讲究 —— 等值条件列在前（user_id），排序列在后（occurred_on）。
-- SQLite 和 PG 的索引语法基本一致。
CREATE INDEX IF NOT EXISTS idx_tx_user_date     ON transactions (user_id, occurred_on DESC);
CREATE INDEX IF NOT EXISTS idx_tx_account_date  ON transactions (account_id, occurred_on DESC);
CREATE INDEX IF NOT EXISTS idx_tx_category_date ON transactions (category_id, occurred_on DESC);

-- =============================================================================
--  触发器
-- =============================================================================
--  为什么余额必须由触发器维护？
--  如果靠应用代码"记完账顺手改一下余额"，只要有一条写入路径忘了改，
--  余额就永久错了 —— 而且没有任何报错，是静默的数据损坏，最难排查。
--  放进数据库，"忘记"这个可能性就不存在了。
--
--  SQLite vs PG 的第二个重要差异（**迁移里最容易出错的地方**）：
--    SQLite：CREATE TRIGGER ... BEGIN ... END，逻辑直接写在触发器里，
--            可以一条触发器挂 INSERT / DELETE / UPDATE 三个事件。
--    PG    ：触发器**不能带逻辑**，必须先写一个函数（LANGUAGE plpgsql），
--            再用 CREATE TRIGGER 把函数挂到表上；而且每个事件要分别挂，
--            并在函数里用 TG_OP 判断是哪种操作。
--
--  另外 PG 的触发器默认是"语句级"，必须显式写 FOR EACH ROW 才是行级 ——
--  忘了写的话不会报错，只是**不会按行触发**，余额就悄悄不更新了。
-- =============================================================================

-- 余额同步函数：一个函数处理 INSERT / UPDATE / DELETE 三种情况
CREATE OR REPLACE FUNCTION fn_tx_sync_balance() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF (TG_OP = 'INSERT') THEN
    UPDATE accounts SET balance_cents = balance_cents + NEW.amount_cents
     WHERE id = NEW.account_id;

  ELSIF (TG_OP = 'DELETE') THEN
    UPDATE accounts SET balance_cents = balance_cents - OLD.amount_cents
     WHERE id = OLD.account_id;

  ELSIF (TG_OP = 'UPDATE') THEN
    -- 先撤销旧值的影响，再施加新值的影响。
    -- 这个"减法技巧"同时正确处理三种情况：改金额、改账户、两者都改。
    UPDATE accounts SET balance_cents = balance_cents - OLD.amount_cents
     WHERE id = OLD.account_id;

    UPDATE accounts SET balance_cents = balance_cents + NEW.amount_cents
     WHERE id = NEW.account_id;
  END IF;

  RETURN NULL;  -- AFTER 触发器的返回值会被忽略
END;
$$;

-- 三个事件分别挂同一个函数。
-- DROP ... IF EXISTS 是必要的：PG 没有 "CREATE TRIGGER IF NOT EXISTS"，
-- 所以重复执行这个脚本时必须先删掉旧的，否则会报 already exists。
DROP TRIGGER IF EXISTS trg_tx_balance ON transactions;

CREATE TRIGGER trg_tx_balance
  AFTER INSERT OR UPDATE OR DELETE ON transactions
  FOR EACH ROW EXECUTE FUNCTION fn_tx_sync_balance();

-- updated_at 自动更新：改流水时自动打时间戳，免得每条 UPDATE 都记得写
CREATE OR REPLACE FUNCTION fn_touch_updated_at() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  NEW.updated_at := now();
  RETURN NEW;    -- BEFORE 触发器必须返回 NEW 才会生效
END;
$$;

DROP TRIGGER IF EXISTS trg_tx_touch ON transactions;

CREATE TRIGGER trg_tx_touch
  BEFORE UPDATE ON transactions
  FOR EACH ROW EXECUTE FUNCTION fn_touch_updated_at();

-- 子分类的 kind 必须和父分类一致。
-- 为什么用触发器？因为 CHECK 只能看当前这一行，无法查询父行的 kind。
-- 遇到"约束需要跨行比较"的场景，触发器就是标准答案（两种数据库都一样）。
CREATE OR REPLACE FUNCTION fn_categories_kind_match() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
  parent_kind text;
BEGIN
  IF NEW.parent_id IS NOT NULL THEN
    SELECT kind INTO parent_kind FROM categories WHERE id = NEW.parent_id;

    -- 父子类型不一致就抛异常。PG 里用 RAISE EXCEPTION，
    -- 对应 SQLite 的 RAISE(ABORT, ...)。
    IF parent_kind IS NOT NULL AND parent_kind <> NEW.kind THEN
      RAISE EXCEPTION '子分类的类型必须和父分类一致';
    END IF;
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_categories_kind_match ON categories;

CREATE TRIGGER trg_categories_kind_match
  BEFORE INSERT OR UPDATE OF kind, parent_id ON categories
  FOR EACH ROW EXECUTE FUNCTION fn_categories_kind_match();
